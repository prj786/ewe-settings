export const isVideo = (p) => /\.(mp4|webm|mkv|mov|avi|m4v)$/i.test(p);
export const isGif = (p) => /\.gif$/i.test(p);

export function parseWallpapersConf(text) {
  const map = {};
  let mode = "fill";
  let mute = true;
  for (const l of String(text).split("\n")) {
    if (l === "" || l[0] === "#") continue;
    const k = l.indexOf("=");
    if (k <= 0) continue;
    const key = l.slice(0, k);
    const val = l.slice(k + 1);
    if (key === "mode") mode = val;
    else if (key === "mute") mute = val === "1";
    else if (key === "backend") continue; // power-user override, script-side only
    else if (val !== "") map[key] = val;
  }
  return { map, mode, mute };
}

export function wallpapersConfText(mode, mute, map) {
  let s = `# AUTO-GENERATED by Settings → Wallpaper. Do not edit by hand.\nmode=${mode}\nmute=${mute ? "1" : "0"}\n`;
  for (const k of Object.keys(map).sort()) s += `${k}=${map[k]}\n`;
  return s;
}

