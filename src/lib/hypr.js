// Pure generation/parsing logic, ported line-for-line from the shell's
// Settings.qml + HyprMon.qml so both writers emit byte-identical files.
// Nothing in here touches the system — that is api.js's job.

// ── Lua helpers ─────────────────────────────────────────────────────────────
export const luaEsc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
export const boolLua = (b) => (b ? "true" : "false");
export const hex6 = (c) => {
  const s = String(c).replace("#", "");
  return s.length === 8 ? s.slice(2) : s;
};

// ── displays (HyprMon.qml) ──────────────────────────────────────────────────
// A spec is the canonical description of one output:
// { desc, name, mode "WxH@Hz", x, y, scale, transform, vrr, bitdepth,
//   disabled, mirror, primary }

export function specFromMonitor(m) {
  let mode = `${m.width || 0}x${m.height || 0}@${Number(m.refreshRate || 60).toFixed(2)}`;
  if (!(m.width > 0) || !(m.height > 0)) {
    const am = m.availableModes || [];
    mode = am.length ? String(am[0]).replace(/Hz$/i, "") : "preferred";
  }
  return {
    desc: m.description || "",
    name: m.name,
    mode,
    x: m.x || 0,
    y: m.y || 0,
    scale: Math.round(Number(m.scale || 1) * 10000) / 10000,
    transform: m.transform || 0,
    vrr: !!m.vrr,
    bitdepth: String(m.currentFormat || "").indexOf("2101010") >= 0 ? 10 : 8,
    disabled: !!m.disabled,
    mirror: m.mirrorOf && m.mirrorOf !== "none" ? m.mirrorOf : "",
    primary: false
  };
}

export const matchId = (s) => (s.desc !== "" ? s.desc : s.name);
export const keyFor = (specs) => specs.map(matchId).sort().join(" || ");
export const modeRes = (mode) => String(mode).split("@")[0];
export const modeHz = (mode) => {
  const p = String(mode).split("@");
  return p.length > 1 ? parseFloat(p[1]) : 60;
};

/** Current live state as a spec list, primary carried over from the profile. */
export function snapshot(monitors, profiles) {
  const out = (monitors || []).map(specFromMonitor);
  const prof = (profiles || {})[keyFor(out)];
  if (prof) {
    for (const s of out) {
      const match = prof.find((p) => matchId(p) === matchId(s));
      if (match) s.primary = !!match.primary;
    }
  }
  if (!out.some((s) => s.primary) && out.length) out[0].primary = true;
  return out;
}

/** The argument table for hl.monitor{} — shared by live apply and monitors.lua */
export function luaArgs(s) {
  const out = s.desc !== "" ? "desc:" + s.desc : s.name;
  let L = `{ output = "${luaEsc(out)}"`;
  if (s.disabled) return L + ", disabled = true }";
  L += `, mode = "${s.mode}", position = "${s.x}x${s.y}", scale = ${s.scale}`;
  if (s.transform) L += `, transform = ${s.transform}`;
  L += `, vrr = ${s.vrr ? 1 : 0}`;
  // always explicit: omitting bitdepth would leave a live 10-bit output at 10
  L += `, bitdepth = ${s.bitdepth === 10 ? 10 : 8}`;
  if (s.mirror !== "") L += `, mirror = "${luaEsc(s.mirror)}"`;
  return L + " }";
}

export function monitorsLuaText(profiles, lastKey) {
  let s =
    "-- AUTO-GENERATED by Settings → Displays (Quickshell). Do not edit by hand.\n" +
    "-- Source of truth: ~/.config/quickshell/display-profiles.json — one profile\n" +
    "-- per connected-monitor set, keyed by the sorted output descriptions.\n" +
    "local profiles = {}\n";
  for (const key of Object.keys(profiles).sort()) {
    s += `profiles["${luaEsc(key)}"] = {\n`;
    for (const spec of profiles[key]) s += "    " + luaArgs(spec) + ",\n";
    s += "}\n";
  }
  s +=
    "\n-- Fallback: at boot the monitor list may not be populated yet, so first\n" +
    "-- assert the last-committed profile unconditionally (desc: rules only bind\n" +
    "-- to outputs that are actually present)…\n" +
    `local last = profiles["${luaEsc(lastKey)}"]\n` +
    "if last then for _, m in ipairs(last) do hl.monitor(m) end end\n" +
    "\n-- …then, when the connected set is known and a different profile matches it\n" +
    "-- (e.g. reload while undocked), let that profile win.\n" +
    "local names = {}\n" +
    "for _, m in ipairs(hl.get_monitors()) do\n" +
    "    local d = m.description\n" +
    '    if d == nil or d == "" then d = m.name end\n' +
    "    names[#names + 1] = d\n" +
    "end\n" +
    "table.sort(names)\n" +
    'local prof = profiles[table.concat(names, " || ")]\n' +
    "if prof and prof ~= last then for _, m in ipairs(prof) do hl.monitor(m) end end\n";
  return s;
}

/** Applied state must match the committed intent; "" = all good. */
export function verifyAgainst(specs, monitors) {
  const bad = [];
  for (const s of specs) {
    const m = (monitors || []).find((x) => matchId(specFromMonitor(x)) === matchId(s));
    if (!m) {
      bad.push(matchId(s) + ": not present");
      continue;
    }
    if (s.disabled) {
      if (!m.disabled) bad.push(m.name + ": should be disabled");
      continue;
    }
    if (m.disabled) {
      bad.push(m.name + ": is disabled");
      continue;
    }
    const live = specFromMonitor(m);
    if (s.mirror !== "") {
      if (live.mirror !== s.mirror) bad.push(m.name + ": mirror not active");
      continue;
    }
    if (modeRes(live.mode) !== modeRes(s.mode))
      bad.push(`${m.name}: mode is ${modeRes(live.mode)}, wanted ${modeRes(s.mode)}`);
    else if (Math.abs(modeHz(live.mode) - modeHz(s.mode)) > 0.6)
      bad.push(`${m.name}: ${modeHz(live.mode).toFixed(0)}Hz, wanted ${modeHz(s.mode).toFixed(0)}Hz`);
    if (live.x !== s.x || live.y !== s.y)
      bad.push(`${m.name}: position ${live.x},${live.y}, wanted ${s.x},${s.y}`);
    if (Math.abs(live.scale - s.scale) > 0.011)
      bad.push(`${m.name}: scale ${live.scale}, wanted ${s.scale}`);
    if (live.transform !== s.transform) bad.push(m.name + ": rotation not applied");
  }
  return bad.join(" · ");
}

/** resolution → refresh-rate map from availableModes (current mode seeded). */
export function modeMapFor(m, spec) {
  const am = m && m.availableModes ? m.availableModes.slice() : [];
  if (spec && spec.mode) am.unshift(spec.mode);
  const byRes = {};
  const resList = [];
  for (const raw of am) {
    const s = String(raw).replace(/Hz$/i, "");
    const res = s.split("@")[0];
    const hz = parseFloat(s.split("@")[1] || "60");
    if (!byRes[res]) {
      byRes[res] = [];
      resList.push(res);
    }
    if (!byRes[res].some((o) => Math.round(o.hz) === Math.round(hz)))
      byRes[res].push({ hz, mode: res + "@" + hz.toFixed(2), label: Math.round(hz) + " Hz" });
  }
  resList.sort((a, b) => {
    const pa = a.split("x"), pb = b.split("x");
    return pb[0] * pb[1] - pa[0] * pa[1];
  });
  for (const r in byRes) byRes[r].sort((a, b) => b.hz - a.hz);
  return { resList, byRes };
}

/** Logical (scaled, rotation-aware) size of a spec. */
export function specW(s) {
  const p = modeRes(s.mode).split("x");
  const w = s.transform % 2 ? p[1] : p[0];
  return Math.max(1, Math.round(w / s.scale));
}
export function specH(s) {
  const p = modeRes(s.mode).split("x");
  const h = s.transform % 2 ? p[0] : p[1];
  return Math.max(1, Math.round(h / s.scale));
}

