// ── hypridle.conf (Screensaver pane) ────────────────────────────────────────

/**
 * saver: { enabled, min, style, lock, lockAfterMin } · lowPower shortens every
 * stage. Mirrors Settings.qml's writeIdleConf() exactly.
 */
export function hypridleConfText(saver, lowPower) {
  const idleScale = lowPower ? 0.5 : 1.0;
  const graceSec = lowPower ? 10 : 20;
  const idleAt = (sec) => Math.max(30, Math.round(sec * idleScale));
  const lockCmd = "qs ipc call lock lock";
  const undim = "qs ipc call saver undim";
  let s =
    "# AUTO-GENERATED by the Quickshell Settings app (Screensaver pane). Do not edit by hand.\n" +
    `# Timeline is ${lowPower ? "BATTERY (shortened)" : "AC"}.\n` +
    "general {\n" +
    `    lock_cmd         = ${lockCmd}\n` +
    `    before_sleep_cmd = ${lockCmd}\n` +
    "    after_sleep_cmd  = hyprctl dispatch 'hl.dsp.dpms(\"on\")'\n" +
    "    ignore_dbus_inhibit = false\n" +
    "}\n";
  const saverSec = idleAt(Math.max(60, Math.round(saver.min * 60)));
  const firstSec = saver.enabled ? saverSec : idleAt(300);
  const dimSec = Math.max(20, firstSec - graceSec);
  s += `listener {\n    timeout    = ${dimSec}\n    on-timeout = qs ipc call saver dim\n    on-resume  = ${undim}\n}\n`;
  if (saver.enabled && !saver.lock) {
    s += `listener {\n    timeout    = ${saverSec}\n    on-timeout = qs ipc call saver show\n    on-resume  = qs ipc call saver hide\n}\n`;
    if (saver.lockAfterMin > 0)
      s += `listener {\n    timeout    = ${saverSec + idleAt(saver.lockAfterMin * 60)}\n    on-timeout = ${lockCmd}\n    on-resume  = ${undim}\n}\n`;
  } else if (saver.enabled && saver.lock) {
    s += `listener {\n    timeout    = ${saverSec}\n    on-timeout = ${lockCmd}\n    on-resume  = ${undim}\n}\n`;
  } else {
    s += `listener {\n    timeout    = ${idleAt(300)}\n    on-timeout = ${lockCmd}\n    on-resume  = ${undim}\n}\n`;
  }
  // Deliberately NOT battery-shortened (matches Settings.qml): suspend is the
  // one stage the user walks into blind — a fixed, documented 15 min instead
  // of a surprise 7.5.
  s += `listener {\n    timeout    = 900\n    on-timeout = ~/.config/hypr/scripts/idle-suspend.sh\n}\n`;
  return s;
}

/** Human description of the timeline the generator above produces. */
export function idlePolicyText(saver, lowPower) {
  const idleScale = lowPower ? 0.5 : 1.0;
  const mins = (m) => Math.max(0.5, Math.round(m * idleScale * 10) / 10);
  const parts = [];
  if (saver.enabled && !saver.lock) {
    parts.push(`screensaver at ${mins(saver.min)} min`);
    parts.push(saver.lockAfterMin > 0 ? `lock at ${mins(saver.min + saver.lockAfterMin)} min` : "no auto-lock");
  } else if (saver.enabled) {
    parts.push(`lock at ${mins(saver.min)} min`);
  } else {
    parts.push(`lock at ${mins(5)} min`);
  }
  parts.push("suspend at 15 min on battery");
  parts.push("no display power-off");
  return parts.join(" · ") + (lowPower ? "   (battery timeline)" : "");
}

// ── shortcuts (SHORTCUTS.md renderer) ───────────────────────────────────────

export function shortcutsModel(md) {
  const out = [];
  for (const raw of String(md).split("\n")) {
    const t = raw.trim();
    if (t.startsWith("## ")) out.push({ h: true, a: t.slice(3), b: "" });
    else if (t.startsWith("|") && t.indexOf("---") < 0) {
      const cells = t.split("|").map((x) => x.trim()).filter((x) => x !== "");
      if (cells.length >= 2 && cells[0].toLowerCase() !== "shortcut")
        out.push({ h: false, a: cells[0].replace(/`/g, ""), b: cells[1].replace(/\*\*/g, "").replace(/`/g, "") });
    }
  }
  return out;
}

