export function parseInputBlocks(text, current) {
  const blocks = String(text).split(/\n\s*\n/).filter((b) => b.trim() !== "");
  const p = { ...current };
  for (let i = 0; i < blocks.length && i < INPUT_OPTIONS.length; i++) {
    const m = blocks[i].split("\n")[0].match(/^(int|float|bool|str):\s?(.*)$/);
    if (!m) continue;
    let v;
    if (m[1] === "int") v = parseInt(m[2]);
    else if (m[1] === "float") v = parseFloat(m[2]);
    else if (m[1] === "bool") {
      const b = m[2].trim();
      v = b === "true" || b === "1";
    } else {
      v = m[2];
      if (v === "[[EMPTY]]") v = "";
    }
    if (v !== undefined && !(typeof v === "number" && isNaN(v))) p[INPUT_OPTIONS[i][1]] = v;
  }
  return p;
}

