export function animLuaLines(m) {
  const L = [];
  if (m <= 0) {
    L.push("hl.config({ animations = { enabled = false } })");
    return L;
  }
  L.push("hl.config({ animations = { enabled = true } })");
  for (const a of ANIM_BASE) {
    const sp = (a.s / m).toFixed(2);
    let s = `hl.animation({ leaf = "${a.leaf}", enabled = true, speed = ${sp}`;
    if (a.spring) s += `, spring = "${a.spring}"`;
    if (a.bz) s += `, bezier = "${a.bz}"`;
    if (a.style) s += `, style = "${a.style}"`;
    L.push(s + " })");
  }
  return L;
}

